import { isNonEmptyString, isOneOf, isPlainObject, isUuid, unknownKeys } from '@basketline/platform'
import { accountTier } from '../db/schema.ts'

export interface OnboardInput {
  name: string
  tier: (typeof accountTier.enumValues)[number]
  /** Seller managers for the retailer's sellers (its own seller IDs, UUIDs). */
  sellerManagers?: { username: string; sellerId: string }[]
}

/** Deleting a tenant: its name, typed again, so a slip can't delete the wrong one. */
export function validateDeleteAccount(body: unknown): string[] {
  if (!isPlainObject(body)) return ['body must be a JSON object']
  const errors = unknownKeys(body, ['confirmName']).map((key) => `unknown field "${key}"`)
  if (!isNonEmptyString(body.confirmName, 200)) errors.push("confirmName must be the tenant's name")
  return errors
}

/** The tenant ID is generated by the server, so a supplied one is an unknown field. */
export function validateOnboard(body: unknown): string[] {
  if (!isPlainObject(body)) return ['body must be a JSON object']
  const errors = unknownKeys(body, ['name', 'tier', 'sellerManagers']).map((key) => `unknown field "${key}"`)
  if (typeof body.name !== 'string' || !isNonEmptyString(body.name.trim(), 200)) errors.push('name must be 1–200 characters')
  if (!isOneOf(body.tier, accountTier.enumValues)) errors.push(`tier must be one of ${accountTier.enumValues.join(', ')}`)
  if (body.sellerManagers !== undefined) {
    const managers = body.sellerManagers
    if (!Array.isArray(managers) || managers.length > 20) errors.push('sellerManagers must be a list of at most 20')
    else
      managers.forEach((manager, i) => {
        if (!isPlainObject(manager) || !isNonEmptyString(manager.username, 100) || !isUuid(manager.sellerId)) {
          errors.push(`sellerManagers[${i}] must be { username, sellerId (UUID) }`)
        }
      })
  }
  return errors
}
